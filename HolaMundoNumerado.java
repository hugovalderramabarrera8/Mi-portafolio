public class HolaMundoNumerado {
    public static void main(String[] args) {
        int contador = 1;

        // O bucle repítese mentres o contador sexa menor ou igual a 100
        while (contador <= 100) {
            System.out.println(contador + ". ¡Hola mundo!");
            contador++; // Incrementamos o contador en 1 en cada volta
        }
    }
}
